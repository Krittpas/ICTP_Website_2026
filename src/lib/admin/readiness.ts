/** จำนวนข้อที่ต้องแก้ก่อนเปิดระบบ — ใช้เป็นป้ายเตือนบนแท็บ "วันงาน" */
export function countBlockers(report: ReadinessReport | null) {
  if (!report) return 0
  return report.checks.filter(c => c.count > 0 && READINESS_LABELS[c.key]?.hard).length
}
